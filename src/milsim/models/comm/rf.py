"""射频通信节点：**唯一**的通信件实现，注册名 ``RF_COMM``。

对应 AFSIM 的 ``WSF_COMM_RCVR`` + ``WSF_COMM_XMTR`` 合在一个部件里的那一半
（通信设备）。这个文件**一行算法都没有**——"通不通"的拓扑在
:mod:`milsim.services.comm`，"按拍投递"在同一个门面里，报文本身
在 :mod:`milsim.services.store`。它存在的意义是**族约定**（§5.7）：
一个实现一个文件、清单只在子包里定义一处。

★ 为什么只有一个实现，而不是"发信机 + 收信机"两个组件
------------------------------------------------------

AFSIM 把通信拆成 ``comm transmitter`` 与 ``comm receiver`` 两个部件，但那是
**七层协议栈**的产物（每一层都要一个对象、一个 ``processInput``）。本版
（用户裁定"通信不要搞的那么复杂"）**不建栈**，于是收发是一件设备的两个方向
——拆成两个部件的话，"这台通信机在哪个网"就有了两个出处（发信机一个、
收信机一个），而它们迟早不同步，症状是"它收得到、发不出"。

⇒ 一个 ``CommNode`` = 一台**双向**通信设备。

★ 参数表就是基类那张，这里**一个都不加**
---------------------------------------

第二步（v0.13.38）接上干扰之后，**收信机那一组参数（功率 / 增益 / 调谐带 /
内损 / 噪声 / ``required_snr_db`` / 极化 / 架高）仍然在基类**，不在本型。
理由：它们不是"射频这一型特有"的——将来做"数据链"或"卫星链路"时，同样是
"一台收信机 + 一条调谐带"，差异只在取值、不在**有哪些项**。拆到子类的话，
"哪些收信机参数是必给的"就有了两个出处，而症状是"换个型号就漏了一项、
干扰悄悄不生效"（§5.15）。

⇒ 本文件**一行算法都没有**：拓扑与压制求值全在 :mod:`milsim.services.comm`。
它存在的意义是**族约定**（§5.7）：一个实现一个文件、清单只在子包里定义一处。
"""

from __future__ import annotations

from ...services.type_registry import register_component
from .base import CommNode


@register_component("RF_COMM")
class RfComm(CommNode):
    """射频通信节点：一个部件 = 一台双向通信设备。

    ★ 参数表**不重复基类那一份**（``CommNode.PARAMS`` 已经是全部）；类继承
    会把它带过来（§5.2 ①）。将来加这一型自己的参数时，用
    ``PARAMS = {**CommNode.PARAMS, "...": ...}`` 合并——**不抄一份**。
    """

    __slots__ = ()


__all__ = ["RfComm"]
