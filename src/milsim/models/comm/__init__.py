"""通信件族包：**通信节点侧**的组件，一个实现一个文件（§5.15）。

.. code-block:: text

    models/comm/
    ├── __init__.py   本文件：只做导出，不含任何实现
    ├── base.py       CommNode    基类（节点参数表 + 登记/注销 + 每拍节拍）
    └── rf.py         RfComm      RF_COMM   射频通信节点（唯一的注册实现）

组织约定与 :mod:`milsim.models.jam` / :mod:`milsim.models.mover` 一样：
**清单只有一份**（下面那个元组），:data:`milsim.models.FRAMEWORK_COMPONENTS`
直接展开它，不另抄一遍。

★ 这一族既像干扰机、又像机动件
------------------------------

* **像干扰机**：装配期往一个门面**登记一次**（"我在哪个网"），关机时注销。
  与干扰机一样，它把自己"是什么"交出去（:class:`CommNodeSpec`），
  "现在能不能通"由门面按整个拓扑回答。
* **像机动件**：**有 ``update`` 节拍**。干扰的求值时机是"受害方检测那一刻"，
  是一个瞬时量；而通信"一个时间步内完成"是一句关于**时间**的话，所以必须有
  每拍节拍去搬报文。

⇒ 于是它落在两者之间：登记是干扰机的路子，节拍是机动件的路子。

★ 每拍的顺序是"提交 → 投递"，不是"投递 → 提交"
----------------------------------------------

用户裁定（原话）："逻辑上应该是先更新状态，若节点状态没变化（干扰、新加节点
等），则延用旧的拓扑。之后再传递信息，否则更新拓扑，重新路由。"

⇒ ``commit()`` 在前、``deliver()`` 在后。反了的话，这一拍投递出去的信会用
**上一拍**的拓扑做路由——被压制的节点还在旧图里，信就还从它走。这个错误
不会报错，只会让"干扰生效了但信还是穿过去了"。

细节见 :mod:`milsim.models.comm.base` 与 :mod:`milsim.services.comm`。
"""

