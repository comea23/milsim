"""地空导弹的制导件：垂直发射 → 程序转弯 → 定高巡航 → 末段比例导引。

为什么单开一张表（而不是套弹道式）
----------------------------------
弹道式（``BALLISTIC_GUIDANCE``）的形状是"竖起来、转到 50°、关掉制导自由飞、
再入后比例导导"——它的中段是 :data:`~milsim.models.guidance.contract.VERT_FREE`：
**没人管垂直**，弹靠重力拱起来。对 20~90 km 的弹道弹这是对的；对**空中目标**
它是错的：一架 8 km 高的飞机在一个"射高 24 km"的中段下面 16 km 处，自由飞的
弧线从它头顶几十公里外掠过去，末段要从天顶方向扎下来——实测（v0.13.66 用
弹道式凑合的那轮）中空 2/6、高空 0/2，全部脱靶，见
``demos/jeff/first_round_gap.md`` 的 G2。

所以地空要的是另一张表：**中段有人管垂直**（定高），把弹稳在目标所在的高度带
附近，末段再用双轴比例导引收口。四段各干一件事：

.. code-block:: text

    LIFTOFF     垂直起飞，保持发射姿态，爬过发射位安全高度
    PITCH_OVER  程序转弯：水平指向目标、垂向拉到爬升角
    CRUISE      定高中段：稳在巡航高度，水平继续追踪
    TERMINAL    双轴比例导引收口

四段的推进条件与选值的理由写在每段的注释里；**这张表的包线是扫出来的**
（见下面"打击包线"），换了数就要连表带包线一起改。

配套弹体（想定里的 ``component_type``）
--------------------------------------
.. code-block:: text

    component_type SAM_BODY : MISSILE_MOVER
        mass             600 kg
        fuel_mass        400 kg
        thrust           66 kN          ← TWR ≈ 11，主动段 ~15 s
        specific_impulse  250 s
        drag_area        0.09 m2
        radial_accel     200 m/s2       ← 20 g：TVC/燃气舵量级
        max_speed        1500 m/s
        launch_fpa       85 deg         ← 垂直发射
    end_component_type

``radial_accel 200`` 是这张表**要的**，而且这个数是**扫出来的**：程序转弯段
要在几秒内把 85° 的发射姿态压到 45° 爬升角，弹在转身完成前不能窜太高——
否则近距低空目标到来时弹还在高空、带着向上的垂直动量，末段来不及压下去
（近×低那一角就是这么丢的）。实测同一张表配三档过载：

======  ==================================================
过载    15 km 处低空目标的结局（3 km / 6 km 两格）
======  ==================================================
40      都打飞（转身 15 s+，窜太高）
120     10 km×3 km 打飞（其余中）
**200** 15 km 及以远全部命中（近界洞只剩 10 km 那一格）
======  ==================================================

**燃料加码救不了远×高，反而压坏近界**：同一张表配 550/700 kg 燃料时远×高
多中一格（40 km×10 km），近×低却退回去（质量大了转身慢）——那是把"能量"
与"敏捷"放在一个旋钮上换。表与弹体是配套的，与 ``asm.py`` 同一条纪律。

**打击包线（实测）**
------------------
进包线 = 制导件判"命中"（起爆距离 ≤ ``lethal_radius 30 m``）。**静态空中
点**（与 ``ballistic.py`` 的包线表同一量法：目标不机动，测的是表与弹体的
几何可达性；机动目标是推演层的事）。另测 30 km 上偏东 5/10 km 两发——只测
正北是不够的：正北的目标上 ``λ̇_h`` 恒为 0，横向环等于没接进去。

=======  ==========  ==========  ==========  ==========  ==========
斜距\\高度  3 km       6 km       8 km       10 km      12 km
=======  ==========  ==========  ==========  ==========  ==========
10 km    打飞        打飞        打飞        命中        命中
15 km    命中        命中        命中        命中        命中
20 km    命中        命中        命中        命中        命中
25 km    命中        命中        命中        命中        命中
30 km    命中        命中        命中        命中        打飞
40 km    命中        命中        命中        打飞        打飞
50 km    命中        命中        命中        打飞        打飞
60 km    命中        命中        命中        打飞        打飞
=======  ==========  ==========  ==========  ==========  ==========

30 km×8 km 偏东 5 km / 10 km：**都命中**（横向环接进去了）。

两个洞，来处都写在这：

- **近×低**（10 km 行在 8 km 以下全飞）：loft 的**最小射程**。弹按固定爬升
  程序起来，临近界时还在高空、带着向上的垂直动量，末段来不及压下去（实测
  末点飞过目标 16 km 后触地）。远程防空弹本来就有最小射程，这一条是物理
  不是 bug。
- **远×高**（40 km 及以远、10 km 以上全飞）：**能量**。主动段只烧 15 s，
  之后纯靠滑翔；往 10 km 以上的目标爬要额外做功，滑翔距离不够。目标在巡航
  高度及以下时重力帮忙，所以 60 km×8 km 反而命中。

**不做的：没有瞄准计算**
------------------------
与弹道式同一个缺口（``ballistic.py`` 模块头"不做的"）：``CRUISE`` 的定高值是
**固定 8000 m**，不管目标在哪个高度带。低空目标（3 km）的几何因此是"从 8 km
上往下扎"，末段要额外拉一个俯冲角——上面那个近×低的洞，根上就是这个缺口，
不是数值问题。按目标高度解算中段高度属于发射计算机的活，等它做进来再收窄。
"""

from __future__ import annotations

from ...services.params import Params
from ...services.type_registry import register_component
from .base import GuidanceComputer
from .contract import (
    HORIZ_PN,
    HORIZ_TARGET,
    VERT_FPA,
    VERT_PN,
    Phase,
    Until,
)

#: 地空导弹的阶段表。**换掉它就是另一种防空弹**（phase 作为组件参数）。
SAM_PHASES: tuple[Phase, ...] = (
    # 垂直起飞段：保持发射姿态。**不写倾角**——那是发射平台的属性（弹体的
    # ``launch_fpa``，这里配 85°），阶段表只管"离开发射位之后往哪飞"。
    # 垂向律留空 ⇒ 推成 1 g 平衡 = 弹道倾角不变，对"保持姿态"正是要的。
    # 1500 m：发射位安全高度（燃气流/离筒），不是战术量。
    Phase(
        "LIFTOFF",
        until=Until.above("altitude", 1_500.0),
    ),
    # 程序转弯段：水平指向目标（追踪导引——此刻目标还远，方位偏差是主要的），
    # 垂向从 85° 压到 45° 爬升角。两个方向同时转，转弯速率受弹体
    # ``radial_accel`` 约束（200 m/s² ⇒ 1000 m/s 时约 11.5 deg/s）。
    # 6000 m：转过弯来、进入中段的高度门限——再低就来不及在目标附近改平。
    Phase(
        "PITCH_OVER",
        until=Until.above("altitude", 6_000.0),
        flight_path_angle=45.0,
        vertical=VERT_FPA,
        horizontal=HORIZ_TARGET,
    ),
    # 定高中段：稳在 8000 m，水平继续追踪（目标机动就慢慢纠方位）。
    # **没有瞄准计算**，定高值是固定的（见模块头"不做的"）：目标在 8 km
    # 附近时这一段是平的，目标低它就变成"壶到上面再往下扎"的前半程。
    # 12000 m：末段交接距离。给末段留 ≈10 s（接近速率 1000+ m/s），
    # 双轴比例导引要从这个距离外把弹修正到航路上。
    Phase(
        "CRUISE",
        until=Until.below("range", 12_000.0),
        altitude=8_000.0,
        horizontal=HORIZ_TARGET,
    ),
    # 末段：双轴比例导引。**不写 max_accel**——过载上限交给弹体
    # （``radial_accel``），制导件只出"想要的方向"。
    Phase(
        "TERMINAL",
        vertical=VERT_PN,
        horizontal=HORIZ_PN,
        gain=4.0,
    ),
)


@register_component("SAM_GUIDANCE")
class SamGuidance(GuidanceComputer):
    """地空弹制导：垂直发射 + 程序转弯 + 定高中段 + 末段双轴比例导引。

    配一个拉得出 12 g 的弹体（``radial_accel 120 m/s2`` 起，见模块头）。
    要另一种防空弹（不同定高、不同交接距离、有无中制导）就派生一个类换掉
    ``phases`` 默认值。
    """

    __slots__ = ()

    PARAMS = {
        **GuidanceComputer.PARAMS,
        #: 剧本。框架给的是上面那张表；要另一种防空弹就在派生类里换掉它。
        "phases": Params.phases(SAM_PHASES),
    }


__all__ = ["SAM_PHASES", "SamGuidance"]
