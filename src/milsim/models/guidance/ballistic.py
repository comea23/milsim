"""弹道导弹的制导件：垂直发射 → 程序转弯 → 自由飞行 → 末段导引（§5.8）。

剧本（AFSIM 的 ``red_icbm_1.txt`` 是同一形状）
----------------------------------------------
.. code-block:: text

    LIFTOFF     近垂直起飞，先离开发射区
    PITCH_OVER  程序转弯到 50°，一直转到发动机关机
    BALLISTIC   关掉制导，让重力接管——**这一段才是"弹道"**
    TERMINAL    再入后开制导，比例导引收口

``BALLISTIC`` 那一段是整件事的关键：它写 ``vertical=VERT_FREE``，法向加速度
为零，于是弹只剩重力与阻力。AFSIM 的表达方式是给 ``guidance_delay`` 一个
大到不可能到的数（``5000 sec``），效果一样但绕了一层——这里直接说"没人管
垂直"。**"弹道"不是一个运动器类型，是"关掉制导"这件事。**

参考配套（弹体的性能参数，写在想定的 ``component_type`` 里）
----------------------------------------------------------
.. code-block:: text

    component_type SSM_SRBM : MISSILE_MOVER
        mass             800 kg
        fuel_mass        400 kg        ← 一半是燃料，固体火箭的常见比例
        thrust            66 kN
        specific_impulse  250 s
        drag_area          0.09 m2
        radial_accel      40 m/s2
        max_speed        1500 m/s
        launch_fpa        85 deg        ← 发射姿态（垂直发射）
    end_component_type

``radial_accel 40 m/s²`` 是推力矢量/燃气舵的量级（4 g 的转向能力），比
巡航弹的 12 大得多——弹道弹在主动段是**靠转发动机喷流**转向的，"转弯半径"
那个概念在这里没有意义。

**射程是算出来的，不是写死的**
----------------------------
不存在一个叫 ``range`` 的参数可以被随便调。实测（``substep 20 ms``，
**有制导件、没有目标**：走完 ``LIFTOFF`` 与 ``PITCH_OVER`` 之后自由飞落地）：

======  ==========  ==========  ==========
燃料    射程        最高        关机速度
======  ==========  ==========  ==========
216 kg   18.0 km     9.9 km      623 m/s
300 kg   30.6 km    14.7 km      859 m/s
**400 kg**  **50.7 km**  **23.4 km**  **1138 m/s**
500 kg   86.5 km    36.9 km     1463 m/s
650 kg  101.4 km    45.5 km     1500 m/s ← 卡在 ``max_speed`` 上
======  ==========  ==========  ==========

``max_speed 1500`` 在 **650 kg** 那一档卡住了（500 kg 的关机速度 1463 m/s
还没到），所以那一档的射程是**被闸门限住的**，不是燃料买来的。

**★ 两个口径都叫"自由飞"，数差一倍，别混。** 上表这一发是"**有制导、但没人
可打**"（程序转弯那 3 s 把倾角从 85° 转到 50°）；**无控弹**在同一起飞倾角上
只有 **29.2 km**（见 :mod:`milsim.models.mover.missile` 的发射角表）。射程的
两段来源因此可以拆开：

.. code-block:: text

    29.2 km  无控（只靠重力转向）
    50.7 km  + 程序转弯（PITCH_OVER 那 3 s，85° → 50°）    +21.5 km
    85.0 km  + 末段比例导引（包线右端）                     +34.3 km

**别拿理想速度增量去估射程**：``Isp·g·ln(m0/mf) = 250·9.8·ln(800/400)
≈ 1.70 km/s``，真空里按 ``R = v²·sin2θ/g`` 算是几百公里——差 10 倍。
差的是**主动段那 15 s 穿过稠密大气时的阻力**（关机时在 4 km 高度上还有
2 g 多的阻力）与重力转向损失。这一条是实测出来的：早先版本照着这个公式
写"50 km 射程"，而实测是 20 km 上下，**公式对、结论错**。

**打击包线（实测）**
------------------
进包线 = 制导件判"命中"（起爆距离 ≤ ``lethal_radius 30 m``）。每个距离都在
**正北**与**往东偏 10 km** 两个目标上测过——只测正北是不够的：横向那条环
（``HORIZ_PN``）在正北的目标上 ``λ̇_h`` 恒为 0，等于没接进去。

=======  ==========  =========================================
目标     结果        最近通过距离（引信不点火，**逐子步**采样）
=======  ==========  =========================================
20 km    打飞        落点在目标前 18.5 ~ 50.9 km
21~24 km 模糊        21/22 km 两个方向都打飞；23 km 起**偏东 10 km**
                     先命中；24 km 偏东 5/10 km 命中；25 km 全中
25 km    命中        0.27 ~ 2.16 m
30 km    命中        0.77 ~ 2.41 m
35 km    命中        2.86 ~ 2.91 m
45 km    命中        0.67 ~ 2.35 m
49 km    命中        0.47 ~ 2.21 m
60 km    命中        0.81 ~ 1.04 m
70 km    命中        0.05 ~ 1.69 m
80 km    命中        0.43 ~ 1.03 m
85 km    命中        0.05 ~ 0.85 m
90 km    打飞        落点在目标前 33.7 ~ 37.7 km
=======  ==========  =========================================

**打飞不是"擦边"，是差着十几到几十公里**：20 km 那一档落点在目标**前面**
18.5 km（偏东 10 km 时是 50.9 km），90 km 那一档差 33.7 km。所以调大
``lethal_radius`` 救不回来——那两端是几何上真的够不着。

下边缘那个"模糊带"的来处：目标一进 **44 km**，末段就开始了，而这时弹还在
程序转弯段里、倾角才转到一半——于是它带着没转完的姿态去追一个咫尺之内的
目标。目标越靠东（越偏离发射方位线），横向那条环越能帮上忙，所以"偏东的先
命中"。这一段是**灵敏的几何**，不是数值不稳定：同一档的三个横向偏移给出
18.5 / 38.2 / 50.9 km 三个差着量级的落点，而每一发本身都是收敛的。

所以**包线是 25~85 km**：纯自由飞只能打 50.7 km，两端差的那一截都是末段
比例导引"收回来 / 补出去"的。最小射程受限于程序转弯段（转不过来的角度就是
打不到的近距离），最大射程受限于末段的转弯能力——都是**算出来的边界**。

**上面第三列要读对**：末段的采样间隔是 ``0.02 s × 400 m/s ≈ 8 m``，所以
"最近通过距离"里那个 ~2 m 是**采样精度**，不是脱靶量——轨迹穿过目标点时，
落在最近点前后 2 m 的那次采样也会读成 ~2 m。真正说明精度的是另一件事：
``lethal_radius`` 收到 **5 m** 时 25~85 km 全部仍然命中。

``detonation_range_m()`` 报的 23~30 m 又是**第三个数**：它是"第一个落进引信
点火区的采样点"的距离，总贴着 ``lethal_radius``。三个数不要混，量法见
:meth:`~milsim.models.guidance.base.GuidanceComputer.detonation_range_m`。

**这张表与 ``docs/00-框架设计.md`` §5.8 的包线表是同一个数**，改了阶段表
就要两张一起改。

**不做的：没有瞄准计算**
------------------------
``PITCH_OVER`` 的倾角是**固定 50°**，不管打多远——真实弹按目标距离解算抬升
角（AFSIM 的 ``WSF_LAUNCH_COMPUTER`` 就是干这个的），于是自由飞的弧线本来就
落在目标附近，末段只需修散布。这里没有那一层，后果有两个：

- 末段要从 **44 km 外**开始修（所以交接距离必须这么大，见阶段表里的注释）；
- 中等射程的"弹道"段很短（49 km 的目标只剩 1.5 s）。

换成"按距离解算抬升角"属于发射计算机的活，等它做进来再收窄交接距离。
"""

from __future__ import annotations

from ...services.params import Params
from ...services.type_registry import register_component
from .base import GuidanceComputer
from .contract import (
    HORIZ_PN,
    VERT_FPA,
    VERT_FREE,
    VERT_PN,
    Phase,
    Until,
)

#: 弹道弹的阶段表。
BALLISTIC_PHASES: tuple[Phase, ...] = (
    # 起飞：保持发射姿态。**不写倾角**——那是发射平台的属性（弹体的
    # ``launch_fpa``，这里配 85°），阶段表只管"离开发射位之后往哪飞"。
    # 垂向律留空，于是推成 1 g 平衡 = 法向加速度为零 = 弹道倾角不变，
    # 对"保持姿态"来说正是要的那个。
    Phase(
        "LIFTOFF",
        until=Until.after(3.0),
    ),
    # 程序转弯：转到 50°，转到关机为止。倾角越小射程越远——这一句就是
    # "打多远"的那个旋钮，而它出现在阶段表里，不出现在参数表里。
    Phase(
        "PITCH_OVER",
        until=Until.event("burnout"),
        flight_path_angle=50.0,
        vertical=VERT_FPA,
    ),
    # 自由飞行：制导关掉，重力接管。垂向律写 VERT_FREE 就是"没人管垂直"，
    # 于是弹道自己拱起来再落下去。这一段的长度**全部**由 `range < 44000`
    # 决定，也就是"导引头截获距离"——这一段才是"弹道弹"这个名字的来处。
    #
    # 44000 这个数是**扫出来的，而且扫了两次**。第一次（v0.13.x）报 28000，
    # 那次的毛病是采样太稀、而且没测 80 km 以上：重扫（12 个距离 × 正北 /
    # 偏东 5 / 10 km 三个目标）发现 28000 在 35 km 与 40 km 上各有一个洞，
    # 而 40000 起 25~85 km 全部命中。边界就在 36000（80 km 上还有一个洞）
    # 与 40000 之间，取 44000 是给自己留一格余量。
    #
    # 方向是对的：**交接越早，末段能用的时间越长，射程边界越远**——"交接太晚
    # 则末段来不及收口"（4 km 处 6 g 只够改 28° 方向）。
    #
    # 代价写在明处：无目标自由飞射程只有 50.7 km，而交接距离 44 km 已经挨着
    # 它了，于是 49 km 的目标只剩 1.5 s 的"弹道"段（80 km 的目标还有 86 s）。
    # 这是 **没有瞄准计算** 的必然结果（见模块头"不做的"）：自由飞的弧线并不
    # 落在目标上，末段比例导引得从 44 km 外一路修过来。
    Phase(
        "BALLISTIC",
        until=Until.below("range", 44_000.0),
        vertical=VERT_FREE,
    ),
    # 再入末段：比例导引收口。中段那一段的落点偏差就是在这里被修掉的。
    Phase(
        "TERMINAL",
        vertical=VERT_PN,
        horizontal=HORIZ_PN,
        gain=4.0,
        max_accel=60.0,
    ),
)


@register_component("BALLISTIC_GUIDANCE")
class BallisticGuidance(GuidanceComputer):
    """弹道弹制导：程序转弯 + 自由飞行 + 末段比例导引。

    这是**参考实现**——想定里直接写 ``component guidance BALLISTIC_GUIDANCE``
    配 ``MISSILE_MOVER``。要另一种弹道弹（不同起飞倾角、不同转弯程序、有没有
    末制导）就派生一个类换掉 ``phases``。
    """

    __slots__ = ()

    PARAMS = {
        **GuidanceComputer.PARAMS,
        "phases": Params.phases(BALLISTIC_PHASES),
    }


__all__ = ["BALLISTIC_PHASES", "BallisticGuidance"]
