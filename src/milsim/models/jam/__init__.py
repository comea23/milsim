"""干扰机族包：**施扰侧**的组件，一个实现一个文件（§5.14）。

.. code-block:: text

    models/jam/
    ├── __init__.py   本文件：只做导出，不含任何实现
    ├── base.py       Jammer      基类（压制核心参数表 + 登记/注销 + 两张卡的钩子）
    └── rf.py         RfJammer    RF_JAMMER   射频干扰机（唯一的注册实现）

组织约定与 :mod:`milsim.models.mover` / :mod:`milsim.models.guidance` 一样：
**清单只有一份**（下面那个元组），:data:`milsim.models.FRAMEWORK_COMPONENTS`
直接展开它，不另抄一遍。

★ 这一族与别的族最不一样的地方：**它没有 ``update``**
-----------------------------------------------------

机动件每帧推进位置、感知件按拍扫描、制导件每子步给指令——都有节拍。
干扰机**没有**，因为 AFSIM 的求值时机是 "at the time a radar detection or
communication attempt occurs"：干扰不是随时间演化的过程，而是**受害方在检测
那一刻去问"现在有多少干扰功率进来"**的一个瞬时量。

于是这一族组件在 ``initialize()`` 里做的事只有一件——把
:class:`~milsim.services.ew.JammerSpec` 交进
:class:`~milsim.services.ew.JamService`；在 ``shutdown()`` 里注销。被击毁 /
关机 / 换频都走这一对入口，不靠时间窗。

★ 求值点在受害侧，所以"探测链"上没有新步骤
------------------------------------------

雷达的八步链一个字都不用改：第 6 步那个 ``S/N`` 变成 ``S/(N+J)``，而 ``J``
是**别人送到第 6 步门口的**（受害方自己算，见
:meth:`milsim.models.percep.base.RadarSensor.received_jamming_w`）。通信接收机
将来接同一个门面，只是在"该收信的那一刻"问同一句话。

★ 只有**一个**注册实现，但一台机器有**三种**效果
------------------------------------------------

``RF_JAMMER`` 的参数表里除压制核心之外还有两组**可选卡**（``deception_*`` /
``false_target_*``），因为压制、欺骗、假目标是同一台机器**同时**具备的效果：

==============  ==============================  ==========================
效果             改了哪一个量                    受害方看到什么
==============  ==============================  ==========================
压制             功率并进噪声 ⇒ ``S/(N+J)``      真目标**更难建航**
欺骗             量测的**中心**被搬走             航迹**建得起来，但是错的**
假目标           航迹表里添**幽灵**               真目标**被挤出去 / 被淹没**
==============  ==============================  ==========================

拆成三个组件类型的话，每一型都得把核心那张参数表再抄一份（同一份功率两个
出处），而且门面规定"一个实体只能有一台干扰机"——"同时压制 + 欺骗"会变成
**写不出来**的配置。细节见 :mod:`milsim.models.jam.rf`。
"""

